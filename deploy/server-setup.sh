#!/usr/bin/env bash
# One-time preparation of a fresh Ubuntu 24.04 Lightsail server. Run as the
# default "ubuntu" user:   bash server-setup.sh <platform-host> <site-base-domain> [reserved,subdomains]
# e.g.                    bash server-setup.sh sites.onekampus.com onekampus.com music,music-admin,music-api
# Safe to re-run: an existing deploy/.env is kept.
set -euo pipefail

PLATFORM_HOST="${1:?platform host, e.g. sites.onekampus.com}"
SITE_BASE_DOMAIN="${2:?site base domain, e.g. onekampus.com}"
RESERVED="${3:-}"
ROOT=/opt/site-platform

echo "› swap (2 GB) for the 1 GB instance"
if ! swapon --show | grep -q /swapfile; then
	sudo fallocate -l 2G /swapfile && sudo chmod 600 /swapfile
	sudo mkswap /swapfile >/dev/null && sudo swapon /swapfile
	echo "/swapfile none swap sw 0 0" | sudo tee -a /etc/fstab >/dev/null
	echo "vm.swappiness=10" | sudo tee /etc/sysctl.d/99-swappiness.conf >/dev/null && sudo sysctl -p /etc/sysctl.d/99-swappiness.conf >/dev/null
fi

echo "› docker + aws cli"
sudo apt-get update -qq
sudo DEBIAN_FRONTEND=noninteractive apt-get install -y -qq docker.io docker-compose-v2 rsync curl unattended-upgrades >/dev/null
sudo usermod -aG docker ubuntu
command -v aws >/dev/null || sudo snap install aws-cli --classic >/dev/null

echo "› folders"
sudo mkdir -p "$ROOT/deploy/data/uploads" "$ROOT/deploy/data/postgres" "$ROOT/backups"
sudo chown -R ubuntu:ubuntu "$ROOT"
# the app container runs as uid 1000 ("node")
sudo chown 1000:1000 "$ROOT/deploy/data/uploads"

ENV="$ROOT/deploy/.env"
if [ ! -f "$ENV" ]; then
	echo "› generating secrets in $ENV"
	umask 077
	cat >"$ENV" <<EOF
# Generated by server-setup.sh — keep private, never commit.
POSTGRES_PASSWORD=$(openssl rand -hex 24)
AUTH_SECRET=$(openssl rand -base64 48 | tr -d '\n')
CRON_SECRET=$(openssl rand -hex 32)
PLATFORM_HOST=$PLATFORM_HOST
SITE_BASE_DOMAIN=$SITE_BASE_DOMAIN
RESERVED_SUBDOMAINS=$RESERVED
# Optional: real email / WhatsApp alerts (until set, alerts are recorded as LOGGED)
# SMTP_HOST=
# SMTP_PORT=587
# SMTP_USER=
# SMTP_PASS=
# SMTP_FROM=
# WHATSAPP_TOKEN=
# WHATSAPP_PHONE_NUMBER_ID=
EOF
else
	echo "› keeping existing $ENV"
fi

echo "› daily jobs (billing at 02:30, backup at 03:00 server time)"
CRON_TMP=$(mktemp)
crontab -l 2>/dev/null | grep -v "site-platform" >"$CRON_TMP" || true
cat >>"$CRON_TMP" <<EOF
30 2 * * * $ROOT/deploy/cron-billing.sh >>$ROOT/backups/cron.log 2>&1 # site-platform
0 3 * * * $ROOT/deploy/backup.sh >>$ROOT/backups/cron.log 2>&1 # site-platform
EOF
crontab "$CRON_TMP" && rm -f "$CRON_TMP"

echo "✓ server ready — now run deploy/deploy.sh from your machine (log out and in once for the docker group)"
